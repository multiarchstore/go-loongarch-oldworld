	MULV	R27, R25, R10
	MULHVU	R27, R25, R11
	ADDV	R10, R12, R12
	SGTU	R10, R12, R9
	ADDV	R11, R13, R13
	ADDV	R9, R13, R13

	// r1 += 38×l2×l4
	MULV	R27, R26, R10
	MULHVU	R27, R26, R11
	ADDV	R10, R14, R14
	SGTU	R10, R14, R9
	ADDV	R11, R15, R15
	ADDV	R9, R15, R15

	// r1 += 19×l3×l3
	MULV	R5, R25, R27
	MULV	R27, R25, R10
	MULHVU	R27, R25, R11
	ADDV	R10, R14, R14
	SGTU	R10, R14, R9
	ADDV	R11, R15, R15
	ADDV	R9, R15, R15

