	MOVV	$38, R6

	MOVV	(R4), R7	// l0
	MOVV	8(R4), R8	// l1
	MOVV	16(R4), R24	// l2
	MOVV	24(R4), R25	// l3
	MOVV	32(R4), R26	// l4

	// r0 = l0×l0
	MULV	R7, R7, R12
	MULHVU	R7, R7, R13

	// r1 = 2×l0×l1
	SLLV	$1, R7, R27
	MULV	R27, R8, R14
	MULHVU	R27, R8, R15

	// r2 = 2×l0×l2
	MULV	R27, R24, R16
	MULHVU	R27, R24, R17

